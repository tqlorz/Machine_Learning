import numpy as np
from whether_linear_separable import whetherLinearSeparable

print("=== 测试线性可分判定函数 ===\n")

# 测试用例1：线性可分的数据集
print("测试1：线性可分数据集")
X1 = np.array([
    [-0.5, 0, -1],
    [3.5, 4.1, -1],
    [4.5, 6, -1],
    [-2, -2.0, -1],
    [-4.1, -2.8, -1],
    [1, 3, -1],
    [-7.1, -4.2, 1],
    [-6.1, -2.2, 1],
    [-4.1, 2.2, 1],
    [1.4, 4.3, 1],
    [-2.4, 4.0, 1],
    [-8.4, -5, 1]
])

Y1 = whetherLinearSeparable(X1)
print(f"结果: Y = {Y1} (期望: 1, 线性可分)")
print()

# 测试用例2：非线性可分的数据集
